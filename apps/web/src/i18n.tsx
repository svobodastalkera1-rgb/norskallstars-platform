export type Message = keyof typeof nb;
const Context = createContext({
  locale: "nb",
  setLocale: (locale: string) => {
    void locale;
  },
  t: (key: Message): string => nb[key],
});
export function Languages({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState("nb");
  const update = (value: string) => {
    setLocale(value);
    document.documentElement.lang = value === "en" ? "en" : "nb";
  };
  return (
    <Context.Provider
      value={{
        locale,
        setLocale: update,
        t: (key) => (locale === "en" ? en : nb)[key],
      }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
